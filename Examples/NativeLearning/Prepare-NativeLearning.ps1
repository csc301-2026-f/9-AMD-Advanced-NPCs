# Link the complete plugin into this host without modifying the shared descriptor.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$plugin = Join-Path $PSScriptRoot 'Plugins/Schola'
$marker = Join-Path $plugin '.generated-by-Prepare-NativeLearning'
if ((Test-Path -LiteralPath $plugin) -and !(Test-Path -LiteralPath $marker)) {
    throw "$plugin exists and was not generated by this script."
}
New-Item -ItemType Directory -Force (Join-Path $plugin 'Source') | Out-Null
Set-Content -LiteralPath $marker -Value "Generated from $root" -Encoding utf8
function Link([string]$Path, [string]$Target) {
    if (Test-Path -LiteralPath $Path) {
        $existing = Get-Item -LiteralPath $Path -Force
        if ($existing.LinkType -ne 'Junction' -or $existing.Target -ne $Target) {
            throw "$Path must be a junction to $Target."
        }
    } else {
        New-Item -ItemType Junction -Path $Path -Target $Target | Out-Null
    }
}
foreach ($folder in @('Config', 'Content', 'Resources', 'Shaders')) {
    $target = Join-Path $root $folder
    if (Test-Path -LiteralPath $target) { Link (Join-Path $plugin $folder) $target }
}
foreach ($module in Get-ChildItem -LiteralPath (Join-Path $root 'Source') -Directory) {
    Link (Join-Path $plugin "Source/$($module.Name)") $module.FullName
}
Copy-Item -LiteralPath (Join-Path $root 'Schola.uplugin') -Destination (Join-Path $plugin 'Schola.uplugin') -Force
Write-Output "Native learning host prepared with every Schola module."
