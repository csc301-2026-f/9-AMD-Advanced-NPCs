"""Print the embedded D4 model header. Requires onnx."""

import onnx
from onnx import TensorProto, helper


def model_bytes(op: str) -> bytes:
    observation = helper.make_tensor_value_info("observation", TensorProto.FLOAT, ["batch", 2])
    action = helper.make_tensor_value_info("action", TensorProto.FLOAT, ["batch", 2])
    graph = helper.make_graph(
        [helper.make_node(op, ["observation"], ["action"])],
        f"D4{op}",
        [observation],
        [action],
    )
    model = helper.make_model(graph, ir_version=8, opset_imports=[helper.make_opsetid("", 13)])
    onnx.checker.check_model(model)
    return model.SerializeToString()


def main() -> None:
    print("// Copyright (c) 2026 Advanced Micro Devices, Inc. All Rights Reserved.")
    print("// Generated by Tools/generate_shared_policy_demo_models.py.")
    print("#pragma once\n\n#include \"CoreTypes.h\"\n")
    print("namespace SharedPolicyD4Models\n{")
    for name, op in (("Toward", "Identity"), ("Away", "Neg")):
        data = model_bytes(op)
        print(f"    inline constexpr uint8 {name}[] = {{")
        for start in range(0, len(data), 12):
            print("        " + ", ".join(f"0x{byte:02x}" for byte in data[start : start + 12]) + ",")
        print("    };")
    print("}")


if __name__ == "__main__":
    main()
