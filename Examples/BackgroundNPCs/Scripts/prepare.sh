# Create Examples/BackgroundNPCs/Plugins/Schola from this repository without
# linking the repository root. A root symlink recurses through
# Examples/BackgroundNPCs/Plugins/Schola. UnrealBuildTool also only discovers
# a .uplugin in a child of a plugin directory, so the descriptor at the
# repository root is not found by AdditionalPluginDirectories.
#
# The generated directory is gitignored. Re-running the script refreshes the
# descriptor copy and relative symlinks. Paths are relative to this file.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
example_dir="$(cd "${script_dir}/.." && pwd)"
repo_root="$(cd "${example_dir}/../.." && pwd)"
descriptor="${repo_root}/Schola.uplugin"
plugin="${example_dir}/Plugins/Schola"
marker="${plugin}/.generated-by-prepare-schola"

if [[ ! -f "${descriptor}" ]]; then
    echo "Schola.uplugin not found at ${repo_root}." >&2
    exit 1
fi
if [[ -L "${plugin}" ]]; then
    echo "${plugin} is a symlink. Remove it and run this script again." >&2
    echo "Do not link Plugins/Schola at the repository root." >&2
    exit 1
fi
if [[ -e "${plugin}" && ! -f "${marker}" ]]; then
    echo "${plugin} exists but was not generated by this script. Move it aside and run again." >&2
    exit 1
fi

mkdir -p "${plugin}/Source"
printf 'Generated from the repository that contains this example.\n' > "${marker}"

link_relative() {
    local link_path="$1"
    local relative_target="$2"
    ln -sfn "${relative_target}" "${link_path}"
}

for folder in Config Content Resources Shaders; do
    if [[ -d "${repo_root}/${folder}" ]]; then
        link_relative "${plugin}/${folder}" "../../../../${folder}"
    fi
done

for module_path in "${repo_root}/Source"/*; do
    [[ -d "${module_path}" ]] || continue
    module_name="$(basename "${module_path}")"
    link_relative "${plugin}/Source/${module_name}" "../../../../../Source/${module_name}"
done

cp -f "${descriptor}" "${plugin}/Schola.uplugin"

if [[ -L "${plugin}/Schola.uplugin" || ! -f "${plugin}/Schola.uplugin" ]]; then
    echo "Schola.uplugin must be a regular file copied into ${plugin}." >&2
    exit 1
fi

while IFS= read -r link_path; do
    target="$(readlink "${link_path}")"
    if [[ "${target}" == /* ]]; then
        echo "Refusing absolute symlink ${link_path} -> ${target}." >&2
        exit 1
    fi
    resolved="$(cd "$(dirname "${link_path}")" && cd "${target}" && pwd)"
    case "${resolved}" in
        "${repo_root}"|"${repo_root}/"* ) ;;
        *)
            echo "Symlink escapes the repository: ${link_path} -> ${resolved}." >&2
            exit 1
            ;;
    esac
    if [[ "${resolved}" == "${repo_root}" ]]; then
        echo "Symlink points at the repository root: ${link_path}." >&2
        exit 1
    fi
done < <(find "${plugin}" -type l)

echo "Schola host plugin ready: ${plugin}"
